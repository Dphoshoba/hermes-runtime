# ---------------------------------------------------------------------------
# File context classification
# ---------------------------------------------------------------------------

FILE_CONTEXT_PRODUCTION = "PRODUCTION"
FILE_CONTEXT_TEST = "TEST"
FILE_CONTEXT_FIXTURE = "FIXTURE"
FILE_CONTEXT_GENERATED = "GENERATED"
FILE_CONTEXT_VENDOR = "VENDOR"
FILE_CONTEXT_CONFIGURATION = "CONFIGURATION"
FILE_CONTEXT_DOCUMENTATION = "DOCUMENTATION"
FILE_CONTEXT_UNKNOWN = "UNKNOWN"

_TEST_PATTERNS = re.compile(
    r"(^tests?/|/tests?/|_test\.py$|_test\.js$|_test\.ts$|"
    r"\.test\.(py|js|ts|tsx|jsx)$|test_/|/test_|"
    r"^test/|/test/|_spec\.(js|ts|jsx|tsx)$|"
    r"__tests__/|\.spec\.(py|js|ts|tsx|jsx)$)",
    re.IGNORECASE,
)

_FIXTURE_PATTERNS = re.compile(
    r"(fixtures?/|__fixtures?__/|testdata/|test_data/|mocks?/|__mocks?__/)",
    re.IGNORECASE,
)

_GENERATED_PATTERNS = re.compile(
    r"(\.generated\.|__pycache__|node_modules/|dist/|build/|\.min\.(js|css)|"
    r"_pb2\.py$|_pb2_grpc\.py$|\.autogenerated)",
    re.IGNORECASE,
)

_VENDOR_PATTERNS = re.compile(
    r"(vendor/|third_party/|external/|\.vendor/)",
    re.IGNORECASE,
)

_CONFIG_PATTERNS = re.compile(
    r"(package\.json$|pyproject\.toml$|setup\.cfg$|setup\.py$|"
    r"Cargo\.toml$|go\.mod$|pom\.xml$|build\.gradle$|"
    r"Makefile$|CMakeLists\.txt$|\.eslintrc|\.prettierrc|"
    r"tsconfig\.json$|webpack\.config|babel\.config|"
    r"Dockerfile$|docker-compose|\.env\.)",
    re.IGNORECASE,
)

_DOCS_PATTERNS = re.compile(
    r"(\.md$|\.rst$|\.txt$|docs?/|CHANGELOG|README|LICENSE|CONTRIBUTING|"
    r"SECURITY|CODE_OF_CONDUCT)",
    re.IGNORECASE,
)


def classify_file_context(file_path: str) -> str:
    """Classify a file path into its operational context."""
    if not file_path:
        return FILE_CONTEXT_UNKNOWN

    path = PurePosixPath(file_path)
    parts = [p.lower() for p in path.parts]

    if _DOCS_PATTERNS.search(file_path):
        return FILE_CONTEXT_DOCUMENTATION
    if _FIXTURE_PATTERNS.search(file_path):
        return FILE_CONTEXT_FIXTURE
    if _GENERATED_PATTERNS.search(file_path):
        return FILE_CONTEXT_GENERATED
    if _VENDOR_PATTERNS.search(file_path):
        return FILE_CONTEXT_VENDOR
    if _CONFIG_PATTERNS.search(file_path):
        return FILE_CONTEXT_CONFIGURATION
    if _TEST_PATTERNS.search(file_path):
        return FILE_CONTEXT_TEST

    return FILE_CONTEXT_PRODUCTION


# ---------------------------------------------------------------------------
# Threshold exceedance ratio
# ---------------------------------------------------------------------------

def compute_exceedance_ratio(observed_lines: int, threshold: int) -> float:
    if threshold <= 0:
        return 0.0
    return round(observed_lines / threshold, 2)


def classify_exceedance_tier(ratio: float) -> str:
    if ratio < 1.1:
        return "NEAR_THRESHOLD"
    if ratio < 2.0:
        return "MODERATE_EXCEEDANCE"
    if ratio < 5.0:
        return "HIGH_EXCEEDANCE"
    return "EXTREME_EXCEEDANCE"


# ---------------------------------------------------------------------------
# Observation / Concern / Actionability inference
# ---------------------------------------------------------------------------

def infer_observation_status(finding: Finding) -> str:
    meta = finding.metadata_json or {}
    evidence = meta.get("evidence_references", [])
    if evidence:
        return "SUPPORTED"
    if finding.description:
        return "SUPPORTED"
    return "UNSUPPORTED"


def infer_concern_status(finding: Finding, file_context: str) -> str:
    if file_context == FILE_CONTEXT_TEST:
        return "INSUFFICIENT"
    if file_context in (FILE_CONTEXT_GENERATED, FILE_CONTEXT_VENDOR):
        return "NOT_MEANINGFUL"
    meta = finding.metadata_json or {}
    evidence = meta.get("evidence_references", [])
    if not evidence:
        return "INSUFFICIENT"
    return "POSSIBLE"


def infer_actionability_status(
    finding: Finding, file_context: str, exceedance_ratio: float | None
) -> str:
    if file_context == FILE_CONTEXT_TEST:
        if exceedance_ratio and exceedance_ratio >= 5.0:
            return "NEEDS_MORE_EVIDENCE"
        return "NOT_ACTIONABLE"
    if file_context in (FILE_CONTEXT_GENERATED, FILE_CONTEXT_VENDOR):
        return "NOT_ACTIONABLE"
    if exceedance_ratio is not None and exceedance_ratio < 1.1:
        return "NEEDS_MORE_EVIDENCE"
    return "NEEDS_MORE_EVIDENCE"


# ---------------------------------------------------------------------------
# Review queue construction
# ---------------------------------------------------------------------------

def _extract_line_count(finding: Finding) -> int | None:
    meta = finding.metadata_json or {}
    evidence = meta.get("evidence_references", [])
    for e in evidence:
        detail = e.get("detail", "")
        m = re.search(r"(\d+)\s*lines", detail)
        if m:
            return int(m.group(1))
    return None


def build_review_queue(
    db: Session,
    repository_id: str | None = None,
    severity: str | None = None,
    category: str | None = None,
    reviewed: bool | None = None,
    limit: int = 50,
    offset: int = 0,
) -> list[dict[str, Any]]:
    q = db.query(Finding)
    if repository_id:
        q = q.filter(Finding.repository_id == repository_id)
    if severity:
        q = q.filter(Finding.severity == severity)
    if category:
        q = q.filter(Finding.category == category)

    findings = q.order_by(Finding.severity, Finding.id).all()

    repo_cache: dict[str, Repository] = {}
    scan_cache: dict[str, ScanJob | None] = {}
    items = []
    for f in findings:
        repo = repo_cache.get(f.repository_id)
        if not repo:
            repo = db.query(Repository).filter(Repository.id == f.repository_id).first()
            if repo:
                repo_cache[f.repository_id] = repo

        if f.repository_id not in scan_cache:
            scan_cache[f.repository_id] = (
                db.query(ScanJob)
                .filter(
                    ScanJob.repository_id == f.repository_id,
                    ScanJob.status == "completed",
                )
                .order_by(ScanJob.completed_at.desc())
                .first()
            )
        scan = scan_cache[f.repository_id]

        file_context = classify_file_context(f.module or "")
        line_count = _extract_line_count(f)
        threshold = 300
        exceedance = compute_exceedance_ratio(line_count, threshold) if line_count else None

        latest_adj = (
            db.query(FindingAdjudication)
            .filter(FindingAdjudication.finding_id == f.id)
            .order_by(FindingAdjudication.reviewed_at.desc())
            .first()
        )

        mission_links = (
            db.query(MissionFindingLink)
            .filter(MissionFindingLink.finding_id == f.id)
            .all()
        )
        mission_ids = [ml.mission_id for ml in mission_links]

        meta = f.metadata_json or {}
        gov_decisions = meta.get("governance_decision", {})

        item = {
            "finding_id": meta.get("finding_id", f.id),
            "db_id": f.id,
            "scan_id": scan.id if scan else None,
            "commit_sha": scan.commit_sha if scan else None,
            "repository_id": f.repository_id,
            "repository_name": repo.name if repo else "UNKNOWN",
            "severity": f.severity,
            "category": f.category,
            "title": f.title,
            "description": f.description or "",
            "module": f.module or "",
            "file_context": file_context,
            "line_count": line_count,
            "exceedance_ratio": exceedance,
            "exceedance_tier": classify_exceedance_tier(exceedance) if exceedance else None,
            "evidence_references": meta.get("evidence_references", []),
            "governance_decision": meta.get("governance_decision", {}).get("decision", "N/A"),
            "governance_rationale": meta.get("governance_decision", {}).get("rationale", ""),
            "observation_status": infer_observation_status(f),
            "concern_status": infer_concern_status(f, file_context),
            "actionability_status": infer_actionability_status(f, file_context, exceedance),
            "mission_linkage": mission_ids if mission_ids else "UNVERIFIED_LEGACY_LINKAGE",
            "current_adjudication": latest_adj.classification if latest_adj else None,
            "operator": latest_adj.operator if latest_adj else None,
            "operator_notes": latest_adj.operator_notes if latest_adj else None,
            "reviewed_at": latest_adj.reviewed_at.isoformat() if latest_adj else None,
        }
        items.append(item)

    total = len(items)
    filtered = items[offset:offset + limit]
    return {"items": filtered, "total": total, "limit": limit, "offset": offset}


