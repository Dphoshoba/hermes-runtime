def create_mission_finding_link(
    db: Session,
    mission_id: str,
    finding_id: str,
    repository_id: str | None = None,
    relationship_type: str = "PRIMARY",
) -> MissionFindingLink:
    existing = (
        db.query(MissionFindingLink)
        .filter(
            MissionFindingLink.mission_id == mission_id,
            MissionFindingLink.finding_id == finding_id,
        )
        .first()
    )
    if existing:
        return existing

    link = MissionFindingLink(
        mission_id=mission_id,
        finding_id=finding_id,
        repository_id=repository_id,
        relationship_type=relationship_type,
    )
    db.add(link)
    db.commit()
    db.refresh(link)
    return link


